// src/types/passport.ts
// Universal Student Career Passport: Single Source of Student Truth across All Academic Domains

export type DataOrigin =
  | "STUDENT_INPUT"       // Entered directly by student
  | "DOCUMENT_EXTRACTED"  // Parsed from uploaded documents (unverified until approved)
  | "VERIFIED_REFERENCE" // Benchmarked against authoritative databases (AISHE, etc.)
  | "AI_SUGGESTION";      // Generated by AI model (NEVER treated as student fact)

export interface PassportProvenanceItem<T> {
  data: T;
  origin: DataOrigin;
  isVerified: boolean;
  sourceNote?: string;
  lastUpdated: Date;
}

export interface StudentPassportSnapshot {
  userId: string;
  name: string;
  email: string;
  mobile: string | null;
  passportScore: number;
  profile: {
    city: string | null;
    state: string | null;
    academicDomain: string | null;
    specialization: string | null;
    educationLevel: string | null;
    institution: string | null;
    course: string | null;
    graduationYear: number | null;
    gradingType: string | null;
    gradeValue: string | null;
    preferredJobRole: string | null;
    targetIndustry: string | null;
    higherEducationGoal: string | null;
    shortTermGoal: string | null;
    longTermGoal: string | null;
    careerInterests: string[];
    studyAbroadCountries: string[];
    achievements: string | null;
    certifications: string | null;
  };
  normalized: {
    educations: Array<{
      id: string;
      level: string;
      institution: string;
      degree: string | null;
      fieldOfStudy: string | null;
      score: string | null;
      scoreType: string | null;
      origin: DataOrigin;
      isVerified: boolean;
    }>;
    skills: Array<{
      id: string;
      name: string;
      category: string | null;
      proficiencyLevel: string | null;
      origin: DataOrigin;
      isVerified: boolean;
    }>;
    projects: Array<{
      id: string;
      title: string;
      description: string;
      role: string | null;
      projectType: string | null;
      toolsOrTechnologies: string[];
      artifactUrl: string | null;
      origin: DataOrigin;
      isVerified: boolean;
    }>;
    experiences: Array<{
      id: string;
      company: string;
      role: string;
      employmentType: string | null;
      experienceType: string | null;
      origin: DataOrigin;
      isVerified: boolean;
    }>;
    achievements: Array<{
      id: string;
      title: string;
      description: string | null;
      category: string | null;
      issuer: string | null;
      origin: DataOrigin;
      isVerified: boolean;
    }>;
  };
}
